#!/usr/bin/env python3
"""Rasterise TrueType/OpenType fonts into 8-bit alpha glyph atlases (C source).

The kernel has no font engine; win32k blends these pre-rendered coverage maps.
Output is committed (kernel/win32k/fontdata.c) so a normal build needs no Pillow.

    python3 tools/mkfont.py > kernel/win32k/fontdata.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont

INTER = "/usr/share/fonts/opentype/inter/"
DEJAVU = "/usr/share/fonts/truetype/dejavu/"
FONTS = [
    # symbol,         file,                              px
    ("GdiFontUi",     INTER + "Inter-Regular.otf",        14),
    ("GdiFontUiBold", INTER + "Inter-SemiBold.otf",       14),
    ("GdiFontSmall",  INTER + "Inter-Medium.otf",         12),
    ("GdiFontMono",   DEJAVU + "DejaVuSansMono.ttf",      14),
    ("GdiFontTitle",  INTER + "InterDisplay-Bold.otf",    30),
    ("GdiFontHuge",   INTER + "InterDisplay-ExtraBold.otf", 64),
]
FIRST, LAST = 32, 126

def emit(sym, path, px):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    blob = bytearray()
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        pad = px
        img = Image.new("L", (adv + 2 * pad, height + 2 * pad), 0)
        ImageDraw.Draw(img).text((pad, pad), ch, font=font, fill=255)
        box = img.getbbox()
        if box is None:
            glyphs.append((len(blob), 0, 0, 0, 0, adv))
            continue
        crop = img.crop(box)
        w, h = crop.size
        glyphs.append((len(blob), w, h, box[0] - pad, box[1] - pad, adv))
        blob += crop.tobytes()
    print(f"/* {sym}: {path.split('/')[-1]} @ {px}px */")
    print(f"static const UCHAR {sym}Bits[{len(blob)}] = {{")
    for i in range(0, len(blob), 24):
        print("    " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    print("};")
    print(f"const GDI_FONT {sym} = {{ {height}, {ascent}, {sym}Bits, {{")
    for g in glyphs:
        print("    { %d, %d, %d, %d, %d, %d }," % g)
    print("} };\n")

print("/* GENERATED by tools/mkfont.py -- do not edit.")
print(" * Glyph coverage maps rasterised from Inter (SIL OFL 1.1) and")
print(" * DejaVu Sans Mono (Bitstream Vera licence). See NOTICE. */")
print('#include "gdi.h"\n')
for f in FONTS:
    emit(*f)
